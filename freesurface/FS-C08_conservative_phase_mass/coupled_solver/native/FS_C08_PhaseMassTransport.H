#ifndef FS_C08_PhaseMassTransport_H
#define FS_C08_PhaseMassTransport_H

#include "fvMesh.H"
#include "volFields.H"
#include "surfaceFields.H"
#include "IOdictionary.H"
#include "Function1.H"
#include "fvmDdt.H"
#include "fvcDiv.H"
#include "fvMatrices.H"

namespace Foam
{
namespace fsC08
{

class PhaseMassTransport
{
    const fvMesh& mesh_;

    IOdictionary material_;

    // Mandatory material/composition provenance and valid temperature domain
    word materialId_;
    word propertySource_;
    scalar Tmin_K_;
    scalar Tmax_K_;
    scalar phaseRelaxation_;

    autoPtr<Function1<scalar>> rhoLiquidT_;
    autoPtr<Function1<scalar>> rhoSolidT_;
    autoPtr<Function1<scalar>> solidMassFractionT_;

    // Composition-specific enthalpy closure; no legacy fvModel latent source.
    dimensionedScalar latentHeat_;
    dimensionedScalar cpSolid_;

    // kg/m3 physical masses per unit mesh volume: conserved variables
    volScalarField mLiquid_;
    volScalarField mSolid_;

    // Independently determined bulk densities, kg/m3
    volScalarField rhoLiquid_;
    volScalarField rhoSolid_;

    // kg/(m3 s), positive liquid -> solid (negative for remelting)
    volScalarField Gamma_;

    // s^-1, local volume creation/consumption ONLY due to phase conversion
    volScalarField SvolPhaseChange_;

    // Absolute fractions of cell volume, not conditional metal fractions
    volScalarField alphaLiquid_;
    volScalarField alphaSolid_;
    volScalarField alphaMetalFromMass_;

    // Face mass flux, kg/s, generated by the real solver's metal VOF flux
    surfaceScalarField liquidMassPhi_;

    bool massFieldsRestarted_;
    bool initialized_;
    label lastSolvedTimeIndex_;

    void checkAndUpdateProperties(const volScalarField& T);
    void initializeIfRequired(const volScalarField& alphaMetal, const volScalarField& T);
    void evaluateGamma(const volScalarField& T);
    void reconstructFractions();

public:

    PhaseMassTransport
    (
        const fvMesh& mesh,
        const volScalarField& initialAlphaMetal,
        const volScalarField& initialT
    );

    // Call once per physical time step from the REAL fluid solver.
    // Metal face flux MUST be MULES-limited native alphaPhi1; this method
    // does not invent velocity or face flux, nor solve pressure itself.
    void solve
    (
        const volScalarField& T,
        const volScalarField& alphaMetal,
        const surfaceScalarField& alphaPhiMetal
    );

    const volScalarField& liquidMass() const { return mLiquid_; }
    const volScalarField& solidMass() const { return mSolid_; }
    const volScalarField& liquidDensity() const { return rhoLiquid_; }
    const volScalarField& solidDensity() const { return rhoSolid_; }
    const volScalarField& gamma() const { return Gamma_; }
    const dimensionedScalar& latentHeat() const { return latentHeat_; }
    const dimensionedScalar& cpSolid() const { return cpSolid_; }
    const volScalarField& phaseVolumeSource() const
    {
        return SvolPhaseChange_;
    }
    const volScalarField& alphaLiquid() const { return alphaLiquid_; }
    const volScalarField& alphaSolid() const { return alphaSolid_; }
    const volScalarField& alphaMetal() const { return alphaMetalFromMass_; }
    const surfaceScalarField& liquidMassFlux() const
    {
        return liquidMassPhi_;
    }
    const word& materialId() const { return materialId_; }
    const word& propertySource() const { return propertySource_; }

    // The following are NOT present until the derived solver integrates
    // pressure, mixture EOS, gas continuity and sensible/latent energy.
    // Do not use this component standalone as a "shrinkage result".
};

} // namespace fsC08
} // namespace Foam
#endif
