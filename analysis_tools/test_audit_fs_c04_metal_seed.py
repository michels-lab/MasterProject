"""FS-C04 static iron initial volume/alpha seed plan; NO field or CFD."""
from __future__ import annotations

import hashlib
import unittest
from unittest.mock import patch

from audit_fs_c03_exterior_mesh import parse
from audit_fs_c04_metal_seed import (
    ORIGINAL, TWO_ZONE, METAL_BLOCKS, REF_CAD_VOLUME_MM3, METAL_CELLS,
    FLUID_CELLS, SAND_CELLS, GAS_CELLS, audit, calculate_metal_block,
)


class MetalSeedTests(unittest.TestCase):
    def test_exact_metal_block_counts_and_analytic_volume(self):
        p=audit()
        self.assertEqual(p["status"],"ANALYTIC_METAL_SEED_IDENTIFIED_NO_FIELD_WRITTEN")
        self.assertEqual(p["original_metal_block_indices"],[9,14,19])
        self.assertEqual(p["initial_metal_cell_count_predicted"],2368)
        self.assertEqual(p["initial_air_cell_count_predicted"],32000)
        self.assertEqual(p["fluid_cells_predicted"],34368)
        self.assertEqual(p["solid_mold_cells_predicted"],7680)
        self.assertAlmostEqual(p["pilot_initial_metal_volume_mm3"],
                               48011.91628,places=5)
        self.assertAlmostEqual(p["reference_CAD_metal_volume_mm3"],
                               REF_CAD_VOLUME_MM3)
        self.assertAlmostEqual(p["pilot_to_CAD_relative_volume_difference"],
                               0.000504697693661,places=10)
        self.assertFalse(p["native_cell_to_block_addressing_verified"])
        self.assertFalse(p["cell_volume_integral_from_native_mesh_verified"])
        self.assertFalse(p["initial_alpha_field_written"])
        self.assertFalse(p["CFD_or_CHT_executed"])

    def test_block_integrals_sum_and_mesh_is_immutable(self):
        old_3=ORIGINAL.read_bytes()
        old_2=TWO_ZONE.read_bytes()
        r=audit()
        v=[p["analytic_volume_mm3"] for p in
           r["original_metal_block_details"]]
        self.assertAlmostEqual(sum(v),48011.91628,places=5)
        self.assertEqual(
            [p["expected_native_cell_count"] for p in
             r["original_metal_block_details"]],[128,960,1280])
        self.assertEqual(ORIGINAL.read_bytes(),old_3)
        self.assertEqual(TWO_ZONE.read_bytes(),old_2)
        self.assertEqual(r["source_3_zone_sha256"],
                         hashlib.sha256(old_3).hexdigest())
        self.assertEqual(r["source_2_zone_sha256"],
                         hashlib.sha256(old_2).hexdigest())

    def test_initial_metal_seed_is_not_mold_or_air(self):
        r=audit()
        self.assertEqual(r["initial_iron_alpha_metal"],1.0)
        self.assertEqual(r["initial_air_alpha_metal"],0.0)
        self.assertFalse(r["mold_region_contains_metal_alpha"])
        self.assertEqual(METAL_CELLS+GAS_CELLS,FLUID_CELLS)
        self.assertEqual(SAND_CELLS,7680)

    def test_wrong_cad_volume_reference_is_a_blocker(self):
        # A stale experimental CAD baseline should cause a review,
        # not be silently accepted as a validated block geometry.
        with patch("audit_fs_c04_metal_seed.REF_CAD_VOLUME_MM3",100_000):
            with self.assertRaisesRegex(ValueError,"too different"):
                audit()

    def test_negative_orientation_or_nonhorizontal_block_rejected(self):
        coords,blocks,_=parse(ORIGINAL.read_text())
        v,_,nc=blocks[METAL_BLOCKS[0]]
        inverted=(v[1],v[0],v[2],v[3],
                  v[5],v[4],v[6],v[7])
        with self.assertRaises(ValueError):
            calculate_metal_block(inverted,nc,coords,9)
        changed=list(coords)
        x,y,z=changed[v[1]]
        changed[v[1]]=(x,y+0.2,z)
        with self.assertRaisesRegex(ValueError,"non-horizontal"):
            calculate_metal_block(v,nc,changed,9)

    def test_no_autogenerated_alpha_field_in_source_repository(self):
        # In this stage there is ONLY an analytic plan, not a field.
        self.assertFalse((TWO_ZONE.parents[1]/"0/fluid/alpha.metal").exists())
        self.assertFalse((TWO_ZONE.parents[1]/"0/alpha.metal").exists())


if __name__=="__main__":
    unittest.main()
